const https = require('https');
const prisma = require('../../config/db');
const intelligenceService = require('./intelligence.service');
const { NotFoundError } = require('../../utils/errors');

class GeminiAuditService {
  /**
   * Helper to execute requests against Google Gemini API with IPv4 connection stability
   */
  async callGeminiApi(prompt) {
    let apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      const path = require('path');
      require('dotenv').config({ path: path.join(__dirname, '../../../.env') });
      apiKey = process.env.GEMINI_API_KEY;
    }
    if (!apiKey) {
      throw new Error('GEMINI_API_KEY is not configured in backend environment.');
    }

    const modelName = process.env.GEMINI_MODEL || 'gemini-1.5-flash';
    const payload = JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.1,
      },
    });

    return new Promise((resolve, reject) => {
      const req = https.request({
        hostname: 'generativelanguage.googleapis.com',
        path: `/v1beta/models/${modelName}:generateContent?key=${apiKey}`,
        method: 'POST',
        family: 4,
        headers: {
          'Content-Type': 'application/json',
          'Content-Length': Buffer.byteLength(payload),
        },
        timeout: 10000,
      }, (res) => {
        let body = '';
        res.on('data', (chunk) => { body += chunk; });
        res.on('end', () => {
          if (res.statusCode < 200 || res.statusCode >= 300) {
            return reject(new Error(`Gemini API responded with status ${res.statusCode}: ${body}`));
          }
          try {
            const data = JSON.parse(body);
            const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
            if (!text) {
              return reject(new Error('Empty response generated by Gemini model.'));
            }
            const cleaned = text.replace(/^```json\s*/i, '').replace(/```\s*$/i, '').trim();
            const parsedJson = JSON.parse(cleaned);
            resolve(parsedJson);
          } catch (e) {
            reject(new Error(`Failed to parse Gemini output as JSON: ${e.message}`));
          }
        });
      });

      req.on('timeout', () => {
        req.destroy();
        reject(new Error('Connection to Gemini API timed out after 10s.'));
      });

      req.on('error', (err) => {
        reject(err);
      });

      req.write(payload);
      req.end();
    });
  }

  /**
   * Performs an AI-assisted compliance gap audit for a specific physical location
   */
  async auditLocationCompliance(locationId, orgId) {
    const location = await prisma.location.findFirst({
      where: { id: locationId, org_id: orgId },
      include: {
        organization: { select: { id: true, name: true, tax_id: true } },
      },
    });

    if (!location) {
      throw new NotFoundError(`Location ${locationId} not found in this organization.`);
    }

    const storeType = (location.type || 'STORE').toUpperCase();
    const jurisdiction = location.state || 'Karnataka';
    const city = location.city || '';

    // 1. Fetch mandatory required license types strictly for this location type and state
    const requiredLicenses = location.type
      ? await prisma.requiredLicenseType.findMany({
        where: {
          location_type: location.type,
          is_mandatory: true,
          OR: [
            { state: null },
            ...(location.state ? [{ state: location.state }] : []),
          ],
        },
        include: { license_type: true },
      })
      : [];

    // 2. Fetch current documents
    const documents = await prisma.document.findMany({
      where: {
        org_id: orgId,
        OR: [
          { location_id: locationId },
          { location_id: null },
        ],
      },
      include: { license_type: true },
      orderBy: { created_at: 'desc' },
    });

    const docMap = new Map();
    for (const d of documents) {
      if (!docMap.has(d.license_type_id)) {
        docMap.set(d.license_type_id, d);
      }
    }

    // Identify missing vs uploaded
    const missingLicenses = [];
    const activeDocuments = [];
    for (const req of requiredLicenses) {
      const lt = req.license_type;
      const doc = docMap.get(lt.id);
      if (!doc) {
        missingLicenses.push(lt);
      } else {
        activeDocuments.push({
          name: lt.name,
          code: lt.code,
          status: doc.status,
          expiryDate: doc.expiry_date ? new Date(doc.expiry_date).toISOString().split('T')[0] : 'None recorded',
        });
      }
    }

    // 3. Fetch cascading dependency risk graph (filtered to applicable licenses)
    const dependencyGraph = await intelligenceService.getLocationDependencyGraph(locationId, orgId);

    // 4. Construct grounded prompt strictly tailored to store-type and location
    const prompt = `
You are the Chief Regulatory Compliance Auditor and AI Copilot for enterprise commercial establishments in India.
Your task is to perform an audit of statutory compliance strictly tailored to this facility.

CRITICAL INSTRUCTIONS FOR FACILITY TYPE & JURISDICTION:
1. STORE / FACILITY TYPE: "${storeType}". JURISDICTION / LOCATION: "${jurisdiction}${city ? ` (${city})` : ''}".
2. You must ONLY evaluate statutory regulations, legal acts, and licensing rules that strictly apply to a "${storeType}" located in "${jurisdiction}".
3. STRICT EXCLUSIONS BASED ON STORE TYPE:
${storeType === 'STORE' || storeType === 'RETAIL' || storeType === 'SHOP' ? `   - This facility is a NON-FOOD COMMERCIAL RETAIL STORE / SHOP.
   - DO NOT suggest or require Food safety (FSSAI) permits unless the business is explicitly described as a food business or restaurant. A retail store does NOT need FSSAI.
   - DO NOT suggest Factories Act (1948), Industrial Boilers, or Hazardous Waste authorizations.
   - Focus strictly on retail commercial obligations in ${jurisdiction}:
     * ${jurisdiction} Shops and Commercial Establishments Act
     * Municipal Trade License / Local Body Commercial Permit
     * Fire Safety No Objection Certificate (Fire NOC)
     * Goods and Services Tax (GST) Registration
     * Corporate Permanent Account Number (PAN)
     * ${jurisdiction} Professional Tax (PT)` : storeType === 'OFFICE' ? `   - This facility is a CORPORATE OFFICE.
   - Strictly focus on white-collar commercial establishment compliance: ${jurisdiction} Shops & Commercial Establishments Act, GST, PAN, Professional Tax, EPF/ESI.
   - DO NOT suggest FSSAI or Factory Acts.` : storeType === 'WAREHOUSE' ? `   - This facility is a LOGISTICS WAREHOUSE / STORAGE FACILITY.
   - Focus on warehouse trade permits, Fire NOC, Sanctioned Building Plan/Occupancy, Environmental/Pollution clearance (SPCB), GST.` : storeType === 'FACTORY' ? `   - This facility is a MANUFACTURING FACTORY.
   - Focus on Factories Act, 1948, State Pollution Control Board (Consent to Operate), Lift/Boiler certifications, Fire NOC, and worker safety.` : `   - Tailor all findings strictly to a ${storeType} in ${jurisdiction}.`}

=== FACILITY DETAILS ===
Location Name: ${location.name}
Facility / Store Type: ${storeType}
Jurisdiction / State: ${jurisdiction}
City: ${city || 'Standard Municipal Area'}
Address: ${location.address || 'Registered corporate facility'}
Employee Count: ${location.employee_count || 'Standard'}
Current Automated Compliance Score: ${location.current_compliance_score ?? 0}%

=== CURRENT UPLOADED COMPLIANCE DOCUMENTS ===
${activeDocuments.length > 0
  ? activeDocuments.map(d => `- ${d.name} (${d.code}) | Status: ${d.status} | Expiry: ${d.expiryDate}`).join('\n')
  : 'None uploaded yet.'
}

=== STATUTORY MANDATORY LICENSES MISSING FOR THIS ${storeType} IN ${jurisdiction} ===
${missingLicenses.length > 0
  ? missingLicenses.map(l => `- ${l.name} (${l.code}) | Issuing Authority: ${l.issuing_authority || 'State/Central Dept'}`).join('\n')
  : 'None - all mandatory licenses have documents on file.'
}

=== CASCADING PREREQUISITE RISKS IDENTIFIED ===
${dependencyGraph.activeRiskChains?.length > 0
  ? dependencyGraph.activeRiskChains.map(c => `- ${c.targetLicense} is BLOCKED because prerequisite ${c.blockedByName} is ${c.reason}`).join('\n')
  : 'No cascading dependency blockages detected.'
}

CRITICAL JSON FORMAT REQUIREMENT:
You must return RAW, VALID JSON ONLY. Do not wrap in markdown or backticks (no \`\`\`json or \`\`\`). The response must be directly converted into objects by JSON.parse() on our end. Match EXACTLY this JSON structure:
{
  "overallHealth": "CRITICAL" | "WARNING" | "COMPLIANT",
  "healthTitle": "Short 3-5 word headline tailored to ${storeType} in ${jurisdiction}",
  "executiveSummary": "2-3 crisp sentences summarizing this ${storeType}'s legal standing under ${jurisdiction} law and immediate risk exposure.",
  "potentialScore": "Target score if action plan followed, e.g. 95%",
  "criticalGaps": [
    {
      "licenseName": "Name of missing or non-compliant license applicable to ${storeType}",
      "statutoryAct": "Relevant statutory Act and section in ${jurisdiction}",
      "penaltyRisk": "Specific fine or operational penalty under the Act in ${jurisdiction}",
      "urgency": "IMMEDIATE" | "HIGH" | "MEDIUM",
      "remediationAdvice": "Concrete instruction for the ${storeType} manager"
    }
  ],
  "cascadingRisks": [
    {
      "blockedLicense": "License waiting on prerequisite",
      "prerequisiteNeeded": "Prerequisite document needed",
      "impact": "Operational consequence if left unresolved"
    }
  ],
  "remediationRoadmap": [
    {
      "step": 1,
      "task": "Concrete step to perform for this ${storeType}",
      "estimatedScoreBoost": "+XX pts",
      "timeline": "e.g. Within 48 hours or Next 7 days"
    }
  ]
}
`;

    try {
      const aiResult = await this.callGeminiApi(prompt);
      return {
        location: {
          id: location.id,
          name: location.name,
          code: location.code,
          type: location.type,
          state: location.state,
          currentScore: location.current_compliance_score ?? 0,
        },
        auditGeneratedAt: new Date().toISOString(),
        model: process.env.GEMINI_MODEL || 'gemini-1.5-flash',
        provider: 'Google Gemini AI',
        analysis: aiResult,
      };
    } catch (err) {
      console.warn('Gemini live call error, generating rule-engine fallback analysis:', err.message);

      // Deterministic fallback if Gemini encounters network hiccups
      const fallbackGaps = missingLicenses.map(l => ({
        licenseName: l.name,
        statutoryAct: `${jurisdiction} Statutory Licensing Regulations`,
        penaltyRisk: 'Notice of non-compliance, statutory fines, and suspension of commercial operations.',
        urgency: 'HIGH',
        remediationAdvice: `Submit official application with ${l.issuing_authority || 'regulatory department'} immediately.`,
      }));

      const chainsByBlockedLicense = new Map();
      for (const c of (dependencyGraph.activeRiskChains || [])) {
        if (!chainsByBlockedLicense.has(c.targetLicense)) {
          chainsByBlockedLicense.set(c.targetLicense, []);
        }
        chainsByBlockedLicense.get(c.targetLicense).push(c.blockedByName);
      }

      const fallbackChains = Array.from(chainsByBlockedLicense.entries()).map(([target, prereqs]) => ({
        blockedLicense: target,
        prerequisiteNeeded: prereqs.join(', '),
        impact: `Cannot secure valid approval for ${target} until prerequisite(s) (${prereqs.join(', ')}) are resolved.`,
      }));

      const fallbackSteps = missingLicenses.slice(0, 3).map((l, idx) => ({
        step: idx + 1,
        task: `Upload valid document for ${l.name}`,
        estimatedScoreBoost: '+20.0 pts',
        timeline: idx === 0 ? 'Within 48 hours' : 'Within 7 business days',
      }));

      return {
        location: {
          id: location.id,
          name: location.name,
          code: location.code,
          type: location.type,
          state: location.state,
          currentScore: location.current_compliance_score ?? 0,
        },
        auditGeneratedAt: new Date().toISOString(),
        model: 'rule-engine-fallback',
        provider: 'Local Compliance Engine',
        analysis: {
          overallHealth: (location.current_compliance_score ?? 0) < 60 ? 'CRITICAL' : 'WARNING',
          healthTitle: `${storeType} Statutory Review & Plan`,
          executiveSummary: `Facility currently operates with ${missingLicenses.length} missing statutory permits and ${fallbackChains.length} cascading blockage${fallbackChains.length === 1 ? '' : 's'} requiring immediate remediation under ${jurisdiction} regulations.`,
          potentialScore: `${Math.min(100, (location.current_compliance_score ?? 0) + (missingLicenses.length * 20))}%`,
          criticalGaps: fallbackGaps,
          cascadingRisks: fallbackChains,
          remediationRoadmap: fallbackSteps,
        },
      };
    }
  }
}

module.exports = new GeminiAuditService();
